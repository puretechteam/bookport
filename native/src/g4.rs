fn code(s: &str) -> (u32, u32) {
    (u32::from_str_radix(s, 2).unwrap(), s.len() as u32)
}

struct Bits {
    out: Vec<u8>,
    acc: u64,
    n: u32,
}

impl Bits {
    fn put(&mut self, (c, bits): (u32, u32)) {
        self.acc = (self.acc << bits) | c as u64;
        self.n += bits;
        while self.n >= 8 {
            self.n -= 8;
            self.out.push((self.acc >> self.n) as u8);
        }
        self.acc &= (1u64 << self.n) - 1;
    }
}

struct Tables {
    term: [[(u32, u32); 64]; 2],
    makeup: [[(u32, u32); 40]; 2], // index n / 64 - 1, for 64 .. 2560
}

fn tables() -> Tables {
    let mut t = Tables { term: [[(0, 0); 64]; 2], makeup: [[(0, 0); 40]; 2] };
    for i in 0..64 {
        t.term[0][i] = code(WHITE[i]);
        t.term[1][i] = code(BLACK[i]);
    }
    for i in 0..27 {
        t.makeup[0][i] = code(WHITE_MAKEUP[i]);
        t.makeup[1][i] = code(BLACK_MAKEUP[i]);
    }
    for i in 0..13 {
        t.makeup[0][27 + i] = code(EXT_MAKEUP[i]);
        t.makeup[1][27 + i] = code(EXT_MAKEUP[i]);
    }
    t
}

fn run(bits: &mut Bits, t: &Tables, color: usize, mut n: usize) {
    while n >= 2560 {
        bits.put(t.makeup[color][2560 / 64 - 1]);
        n -= 2560;
    }
    if n >= 64 {
        bits.put(t.makeup[color][(n & !63) / 64 - 1]);
        n &= 63;
    }
    bits.put(t.term[color][n]);
}

fn changes(row: &[u8], w: usize, out: &mut Vec<usize>) {
    out.clear();
    let mut prev = 0u8;
    for x in 0..w {
        let v = (row[x / 8] >> (7 - x % 8)) & 1;
        if v != prev {
            out.push(x);
            prev = v;
        }
    }
}

pub fn encode(packed: &[u8], w: usize, h: usize) -> Vec<u8> {
    let t = tables();
    let nb = (w + 7) / 8;
    let mut bits = Bits { out: Vec::new(), acc: 0, n: 0 };
    let mut rf: Vec<usize> = Vec::new();
    let mut cur: Vec<usize> = Vec::new();
    for y in 0..h {
        let row = &packed[y * nb..(y + 1) * nb];
        if row.iter().any(|&b| b != 0) {
            changes(row, w, &mut cur);
        } else {
            cur.clear();
        }
        let mut a0: i64 = -1;
        let mut col = 0usize;
        let mut j = 0usize;
        loop {
            let a1 = if j < cur.len() { cur[j] } else { w };
            // first change on the reference line right of a0 with the opposite colour
            let mut k = rf.partition_point(|&c| (c as i64) <= a0);
            if (k & 1) != col {
                k += 1;
            }
            let b1 = if k < rf.len() { rf[k] } else { w };
            let b2 = if k + 1 < rf.len() { rf[k + 1] } else { w };
            if b2 < a1 {
                bits.put((1, 4));
                a0 = b2 as i64;
                continue;
            }
            let d = a1 as i64 - b1 as i64;
            if (-3..=3).contains(&d) {
                bits.put(match d {
                    0 => (1, 1),
                    1 => (3, 3),
                    -1 => (2, 3),
                    2 => (3, 6),
                    -2 => (2, 6),
                    3 => (3, 7),
                    _ => (2, 7),
                });
                a0 = a1 as i64;
                col ^= 1;
                j += 1;
            } else {
                let a2 = if j + 1 < cur.len() { cur[j + 1] } else { w };
                bits.put((1, 3));
                run(&mut bits, &t, col, a1 - a0.max(0) as usize);
                run(&mut bits, &t, col ^ 1, a2 - a1);
                a0 = a2 as i64;
                j += 2;
            }
            if a0 >= w as i64 {
                break;
            }
        }
        std::mem::swap(&mut rf, &mut cur);
    }
    bits.put((1, 12));
    bits.put((1, 12));
    if bits.n > 0 {
        let b = (bits.acc << (8 - bits.n)) as u8;
        bits.out.push(b);
    }
    bits.out
}
